function seedTableVersions(tables: WarehouseTable[]): TableVersion[] {
  const out: TableVersion[] = tables.map((t) => ({
    id: `tv-${t.id}-1`,
    tableId: t.id,
    projectId: t.projectId,
    version: 1,
    createdAt: '2026-08-01 10:00',
    createdBy: '张三',
    note: '初始发布',
    snapshot: snapshotTable(t),
  }));
  const first = out.find((v) => v.tableId === 'tbl-dwd-order-item');
  const cur = tables.find((t) => t.id === 'tbl-dwd-order-item');
  if (first && cur) {
    first.snapshot = {
      ...first.snapshot,
      comment: '交易域-订单项明细（未退化地区）',
      columns: first.snapshot.columns.filter((c) => c.name !== 'region'),
    };
    out.push({
      id: 'tv-tbl-dwd-order-item-2',
      tableId: cur.id,
      projectId: cur.projectId,
      version: 2,
      createdAt: '2026-08-15 14:20',
      createdBy: '李四',
      note: '退化地区维度',
      snapshot: snapshotTable(cur),
    });
  }
  return out;
}

